"""숫자를 문장으로 바꾸는 규칙 모듈 — CLAUDE.md 1절("원인 분석·개선 제안 자동
작성 금지")·6절("판단이 필요한 문장은 사람이 쓴다")을 문장 생성 단계에서
강제하기 위한 어휘 규칙만 담는다.

이 모듈이 아는 것과 모르는 것:
  - 안다: 값 하나·전월 대비 변화 하나를 어떤 문장 모양으로 표현할지.
  - 모른다: 그 변화가 좋은지 나쁜지, 원인이 무엇인지. 그건 사람이 5·6장에 쓴다.

fmt_value가 받는 "유형"은 metrics_catalog의 원본 frontmatter 값이 아니라
"금액형"/"비율형"/"카운트형" 중 이미 하나로 정해진 표시 종류여야 한다. 파생형·
변화율형처럼 유형 문자열만으로 표시 종류를 못 정하는 지표는(예: monthly_churn_rate)
common.py의 `_display_kind`처럼 카탈로그를 따라 올라가 미리 판별한 뒤 이 함수에
넘겨야 한다 — 이 모듈은 카탈로그를 받지 않으므로 그 판별을 대신할 수 없다.
"""

from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 함수 1 — 값 하나를 문장 조각으로
# ---------------------------------------------------------------------------

def fmt_value(value, 유형: str, 지표명: str) -> str:
    """계산된 값 하나를 화면·문장에 쓸 문자열로 바꾼다.

    지표명의 "데이터 사용량" 문구를 유형 검사보다 먼저 보는 이유: avg_data_usage는
    calc_metrics.py의 코드 제약 때문에 유형이 "금액형"으로 적혀 있지만 실제 단위는
    GB다(위키 06_metrics/avg_data_usage.md에 기록된 실측 사례 — 이 오탐 때문에
    한 번 "22원"으로 잘못 표시된 적이 있다). metrics_catalog를 못 받는 이 함수는
    "표시단위" 필드를 볼 수 없으므로, 대신 지표명 자체의 문구로 같은 오탐을
    피한다. 그래서 이 검사가 금액형/비율형/카운트형 분기보다 앞에 있어야 한다.
    """
    if value is None or (isinstance(value, float) and value != value):
        return "값 없음"

    지표명 = 지표명 or ""
    유형 = 유형 or ""

    # "데이터 사용량"이 지표명에 있다는 것만으로 GB로 단정하지 않는다 —
    # usage_decline_rate_3m("3개월 데이터 사용량 감소율")도 이름에 같은 문구가
    # 들어있지만 실제 값은 GB가 아니라 감소율(비율)이다(실측으로 확인함, 이걸
    # 안 걸러내면 -0.016을 "0.0 GB"로 잘못 표시한다). avg_data_usage처럼
    # "유형이 금액형인데 실제 단위는 GB다"인 경우만 걸러내야 하므로 유형 조건을
    # 같이 본다.
    if 유형.startswith("금액형") and "데이터 사용량" in 지표명:
        return f"{value:,.1f} GB"

    if 유형.startswith("금액형"):
        return f"{value:,.0f}원"
    if 유형.startswith("비율형"):
        # 저장된 값은 0.05(=5%) 같은 소수다 — 표시할 때만 100을 곱한다.
        return f"{value * 100:.1f}%"
    if 유형.startswith("카운트형"):
        unit = "명" if "고객" in 지표명 else "건"
        return f"{value:,.0f}{unit}"

    # 파생형·변화율형처럼 이 함수가 판별할 수 없는 유형이 그대로 들어온 경우.
    # 추측해서 원/%/GB 단위를 붙이지 않는다 — 단위 없는 숫자로 남겨 "이 값의
    # 단위를 이 함수가 모른다"는 사실을 숨기지 않는다.
    return f"{value:,.1f}"


# ---------------------------------------------------------------------------
# 함수 2 — 전월 대비 변화를 문장 조각으로
# ---------------------------------------------------------------------------

def fmt_change(row) -> str:
    """전월 대비 변화를 "절대변화 (상대변화율)" 형태로 만든다. row는
    pipeline/compare.py의 compare()가 만드는 한 행(dict 또는 Series)이다 —
    지표명·유형·절대변화·상대변화율·퍼센트포인트변화·비교상태 키를 기대한다.

    절대변화 대신 %p를 쓰는 지표를 구분하는 이유: compare.py는 이미 "이 지표가
    비율인가"를 (파생형까지 포함해) 판별해서 퍼센트포인트변화 컬럼에 넣어준다.
    이 함수는 그 판별을 다시 하지 않고 그 컬럼이 채워져 있는지만 본다 — 같은
    판단을 두 곳에서 다르게 하면 화면·리포트가 어긋난다.
    """
    if row.get("비교상태") == "비교 불가":
        return "전월 자료 없음 — 비교 불가"

    지표명 = row.get("지표명") or row.get("metric_id", "")
    유형 = row.get("유형", "")
    절대변화 = row.get("절대변화")
    상대변화율 = row.get("상대변화율")
    pp = row.get("퍼센트포인트변화")

    if 절대변화 is not None and 절대변화 == 0:
        return "변화 없음 (0.00%)"

    상대변화율_없음 = 상대변화율 is None or (isinstance(상대변화율, float) and 상대변화율 != 상대변화율)
    율_str = "비율 계산 불가(전월 값 0)" if 상대변화율_없음 else f"{상대변화율:+.2f}%"

    pp_있음 = pp is not None and not (isinstance(pp, float) and pp != pp)
    if pp_있음:
        크기_str = f"{pp:+.1f}%p"
    elif 절대변화 is None:
        크기_str = "값 없음"
    else:
        부호 = "+" if 절대변화 > 0 else "-"
        크기_str = f"{부호}{fmt_value(abs(절대변화), 유형, 지표명)}"

    return f"{크기_str} ({율_str})"


# ---------------------------------------------------------------------------
# 함수 3 — 계산 결과 한 건을 사실 문장으로
# ---------------------------------------------------------------------------

def describe_metric(row, status: str) -> str:
    """지표 값 하나를 근거 강도에 맞는 한 문장으로 만든다. row는 metrics_df
    한 행(dict 또는 Series) — 지표명·유형·value(또는 당월)·sample_size 키를
    기대한다.

    status를 row["status"]에서 읽지 않고 별도 인자로 받는 이유: 호출자가 이미
    필터링했거나 다른 시점의 status를 문장에 반영해야 할 수 있다(예: 재계산
    후 대조). row 안의 값을 암묵적으로 신뢰하면 호출자의 판단이 문장에
    반영되지 않는다.

    "유효구간 밖"·"계산오류"는 값을 절대 만들어내지 않는다(CLAUDE.md 9절 —
    0으로 조용히 처리하는 것과 같은 실수를 문장에서도 반복하지 않는다).
    """
    지표명 = row.get("지표명") or row.get("metric_id", "")
    유형 = row.get("유형", "")
    value = row.get("value", row.get("당월"))
    값 = fmt_value(value, 유형, 지표명)

    if status == "OK":
        문장 = f"{지표명}은 {값}이다."
    elif status == "구간확장":
        문장 = f"{지표명}은 {값}이다(정의서 유효구간 밖, 확장 승인)."
    elif status == "표본부족":
        n = row.get("sample_size")
        n_str = f"{n:.0f}" if isinstance(n, (int, float)) and n == n else "알 수 없는"
        문장 = f"{지표명}은 {값}으로 나타나나 표본 {n_str}건으로 기준 미달이어서 근거로 쓰지 않는다."
    elif status == "유효구간 밖":
        문장 = f"{지표명}은 정의서 유효구간 밖이라 이번 실행에서 계산되지 않았다."
    elif status == "계산오류":
        문장 = f"{지표명}은 계산 중 오류가 발생해 값을 낼 수 없다."
    else:
        문장 = f"{지표명}의 상태를 확인할 수 없다({status})."

    if row.get("임계값_상태") == "잠정":
        문장 += " (임계값 잠정)"

    return 문장


# ---------------------------------------------------------------------------
# 함수 4 — 전월 대비 변화를 사실 문장으로
# ---------------------------------------------------------------------------

def describe_change(row, threshold: float) -> str:
    """전월 대비 변화 한 건을 문장으로 만든다. row는 fmt_change와 같은 모양의
    comparison_df 한 행을 기대한다.

    방향(증가/감소)에 좋다·나쁘다를 붙이지 않는 이유: 임계값을 넘었다는 건
    "확인이 필요하다"는 신호일 뿐이다. 예를 들어 이탈률 감소와 활성고객 감소는
    같은 "감소"지만 하나는 반갑고 하나는 아니다 — 어느 쪽인지는 지표 성격과
    업무 맥락을 아는 사람만 판단할 수 있다(CLAUDE.md 6절: 그 판단은 자동화
    범위 밖이라고 명시하고, 5·6장에 사람이 쓰게 비워둔 이유와 같다).
    """
    지표명 = row.get("지표명") or row.get("metric_id", "")

    if row.get("비교상태") == "비교 불가":
        return f"{지표명}은 전월 자료가 없어 비교할 수 없다."

    상대변화율 = row.get("상대변화율")
    if 상대변화율 is None or (isinstance(상대변화율, float) and 상대변화율 != 상대변화율):
        return f"{지표명}은 전월 대비 비율을 계산할 수 없다(전월 값 0)."

    변화 = fmt_change(row)
    if abs(상대변화율) >= threshold:
        return f"{지표명}은 전월 대비 {변화}로 임계값 {threshold}%를 초과했다."
    return f"{지표명}은 전월 대비 {변화}로 임계값 이내다."


# ---------------------------------------------------------------------------
# 함수 5 — 금지 표현 자체 검사
# ---------------------------------------------------------------------------

# CLAUDE.md 1절·6절이 사람 몫으로 못박은 세 갈래(인과 단정·제안·가치판단)를
# 그대로 어휘 목록으로 옮긴다. 목록을 늘리면 이 파일에서만 늘린다 — 문장을
# 만드는 함수(1~4) 안에 금칙어 검사를 흩어두면 나중에 어디를 고쳐야 하는지
# 찾기 어려워진다.
FORBIDDEN_PHRASES = {
    "인과": ["때문", "탓", "원인은"],
    "제안": ["해야", "필요하다", "권장", "제안"],
    "가치판단": ["개선", "악화", "우려", "심각", "양호", "positive", "negative"],
}

# "따라서 ~이다"는 고정 문구가 아니라 문형이라 위 리스트로 못 잡는다. 문장
# 하나를 벗어나 다음 문장까지 걸리지 않도록 줄바꿈·마침표 앞에서 멈춘다.
_CAUSAL_PATTERN = re.compile(r"따라서[^.\n]*?이다")


def check_forbidden(text: str) -> list:
    """text 안에서 인과 단정·제안·가치판단 표현을 찾아 목록으로 반환한다.
    빈 리스트면 걸린 게 없다는 뜻이다.

    리포트를 만든 뒤 이 함수로 자체 검사하는 이유: describe_* 함수들이 규칙을
    지켜 문장을 만들어도, 나중에 누군가 문장 조각을 손으로 이어붙이거나
    새 문장을 추가하면서 금칙어가 섞여 들어갈 수 있다. 생성 시점에 규칙을
    지키는 것과, 완성된 텍스트를 검사해서 확인하는 것은 서로 다른 방어선이다
    — 후자가 없으면 사람이 리포트 전체를 다시 읽어야 알 수 있다.
    """
    findings = []
    for 분류, phrases in FORBIDDEN_PHRASES.items():
        for phrase in phrases:
            for m in re.finditer(re.escape(phrase), text, flags=re.IGNORECASE):
                findings.append({"분류": 분류, "표현": phrase, "위치": m.start()})

    for m in _CAUSAL_PATTERN.finditer(text):
        findings.append({"분류": "인과", "표현": m.group(0), "위치": m.start()})

    findings.sort(key=lambda f: f["위치"])
    return findings
